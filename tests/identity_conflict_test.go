package parser_test

import (
	"fmt"
	"testing"

	"github.com/mia0x75/pgparser/ast"
	"github.com/mia0x75/pgparser/parser"
)

func TestParseAlterIdentityConflict(t *testing.T) {
	for _, column := range []string{"COLUMN ", ""} {
		for _, mode := range []struct {
			sql  string
			when byte
		}{
			{"ALWAYS", 'a'},
			{"BY DEFAULT", 'd'},
		} {
			for _, options := range []string{"", " ()", " (START WITH 3 INCREMENT BY 2)"} {
				sql := fmt.Sprintf("ALTER TABLE alignment_t ALTER %sid ADD GENERATED %s AS IDENTITY%s", column, mode.sql, options)
				t.Run(sql, func(t *testing.T) {
					if column == "" && options == " ()" {
						if _, err := parser.New().ParseOneStmt(sql); err == nil {
							t.Fatal("accepted empty identity options without COLUMN")
						}
						return
					}
					stmt := mustParseOne(t, sql).(*ast.AlterTableStmt)
					if len(stmt.Specs) != 1 || stmt.Specs[0].OldColumnName == nil || stmt.Specs[0].OldColumnName.Name != "id" {
						t.Fatalf("identity command = %#v", stmt)
					}
					spec := stmt.Specs[0]
					if spec.Tp != ast.AlterTableGeneric {
						t.Fatalf("identity command type = %v", spec.Tp)
					}
					// Preserve the existing AST contract while removing the shadowed production.
					if column != "" {
						if spec.Def != nil {
							t.Fatalf("COLUMN identity definition = %#v, want nil", spec.Def)
						}
					} else {
						constraint, ok := spec.Def.(*ast.Constraint)
						if !ok || constraint.GeneratedWhen != mode.when {
							t.Fatalf("identity definition = %#v, want mode %c", spec.Def, mode.when)
						}
					}
				})
			}
		}
	}
}

func TestParseAlterIdentityConflictRejectsMalformed(t *testing.T) {
	for _, tail := range []string{
		"ADD GENERATED AS IDENTITY",
		"ADD GENERATED ALWAYS IDENTITY",
		"ADD GENERATED BY AS IDENTITY",
		"ADD GENERATED BY DEFAULT AS",
		"ADD GENERATED ALWAYS AS IDENTITY (START WITH)",
		"ADD GENERATED ALWAYS AS IDENTITY () unexpected",
	} {
		for _, column := range []string{"COLUMN ", ""} {
			sql := "ALTER TABLE alignment_t ALTER " + column + "id " + tail
			t.Run(sql, func(t *testing.T) {
				if _, err := parser.New().ParseOneStmt(sql); err == nil {
					t.Fatal("accepted malformed identity command")
				}
			})
		}
	}
}
