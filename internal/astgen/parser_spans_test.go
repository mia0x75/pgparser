package main

import (
	"bytes"
	"go/ast"
	"go/parser"
	"go/token"
	"strings"
	"testing"
)

func TestInjectParserSpans(t *testing.T) {
	const source = `// Code generated by goyacc. DO NOT EDIT.
package parser

// semantic carries grammar values.
type semantic struct { node Node }

func reduce(yynt int) {
switch yynt {
case 1:
    {
        yyVAL.node = makeNode()
    }
case 2:
    {
        if enabled { yyVAL.list = makeList() }
    }
case 3:
    yyVAL.str = "name"
}
}
`
	first, err := injectParserSpans([]byte(source))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(first), "// Code generated by goyacc. DO NOT EDIT.\n") {
		t.Fatal("generated header moved")
	}
	f, err := parser.ParseFile(token.NewFileSet(), "parser.go", first, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	if !ast.IsGenerated(f) || f.Decls[0].(*ast.GenDecl).Doc.Text() != "semantic carries grammar values.\n" {
		t.Fatal("declaration comments moved")
	}
	for _, call := range []string{
		"setSyntaxSpan(yyVAL.node, yyVAL.span)",
		"setSyntaxSpan(yyVAL.list, yyVAL.span)",
	} {
		if strings.Count(string(first), call) != 1 {
			t.Fatalf("missing or duplicate call %s", call)
		}
	}
	second, err := injectParserSpans(first)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, second) {
		t.Fatalf("span injection is not idempotent:\nfirst:\n%s\nsecond:\n%s", first, second)
	}
}
